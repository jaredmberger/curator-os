import { buildPublicationPayload } from './publication-export.js';

const SUPPORTED_TYPES = new Set(['ship', 'company', 'organization']);

export function buildGeneratedPagePackage(record = {}, records = []) {
  const payload = buildPublicationPayload(record, records);
  return {
    format: 'curatoros-generated-page-package',
    formatVersion: 1,
    filename: `${safeName(record.id)}.html`,
    html: renderGeneratedPage(payload),
    publication: payload
  };
}

export function renderGeneratedPage(payload) {
  const record = payload.record;
  const details = Object.entries(record.details || {}).map(([label, value]) => `<div><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`).join('');
  const relationships = (record.relationships || []).map((item) => `<li><strong>${escapeHtml(item.relationship)}</strong><span>${escapeHtml(item.targetTitle || item.target)} · ${escapeHtml(item.confidence)}</span></li>`).join('') || '<li>No relationships recorded.</li>';
  const sources = (record.sources || []).map((source) => `<li><strong>${escapeHtml(source.title || source.id)}</strong>${source.citation ? `<span>${escapeHtml(source.citation)}</span>` : ''}</li>`).join('') || '<li>No sources recorded.</li>';
  const structured = escapeHtml(JSON.stringify(payload.structuredData, null, 2));
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${escapeHtml(record.title)}</title><meta name="description" content="${escapeHtml(record.summary)}"><script type="application/ld+json">${JSON.stringify(payload.structuredData)}</script></head><body class="olc-generated-page" data-curatoros-record="${escapeHtml(record.id)}"><main><header class="olc-page-hero"><span class="olc-eyebrow">${escapeHtml(record.type)}</span><h1>${escapeHtml(record.title)}</h1><p>${escapeHtml(record.summary)}</p></header><section><h2>Canonical details</h2><dl>${details || '<div><dt>Details</dt><dd>No details recorded.</dd></div>'}</dl></section><section><h2>Relationships</h2><ul>${relationships}</ul></section><section><h2>Sources</h2><ul>${sources}</ul></section><section><h2>Structured data</h2><pre>${structured}</pre></section><footer><p>Generated by CuratorOS. Preview only; not deployed.</p></footer></main></body></html>`;
}

export function renderPagePackageDialog(records = [], selectedId = null) {
  const record = selectedId ? records.find((item) => item.id === selectedId) : null;
  const supported = record && SUPPORTED_TYPES.has(record.type);
  let preview = '';
  let blocked = '';
  if (supported) {
    try {
      preview = renderGeneratedPage(buildPublicationPayload(record, records));
    } catch (error) {
      blocked = error instanceof Error ? error.message : String(error);
    }
  }
  return `<dialog class="cos-authoring-dialog cos-authoring-dialog-wide" data-page-package-dialog><div class="cos-authoring-form"><header><div><span class="cos-eyebrow">Publication workspace</span><h2>Generated page package</h2></div><button type="button" data-close-dialog aria-label="Close">×</button></header><p class="cos-authoring-help">Review the complete generated page before deployment. Canonical records are never changed.</p>${supported ? blocked ? `<p class="cos-form-error">${escapeHtml(blocked)}</p>` : `<section><h3>${escapeHtml(record.title)}</h3><iframe title="Generated page preview" srcdoc="${attr(preview)}"></iframe><button type="button" data-download-page-package>Download HTML + JSON package</button></section>` : '<p>Select a ship, builder, or shipping line first.</p>'}<footer><button type="button" data-close-dialog>Close</button></footer></div></dialog>`;
}

export function installPagePackagePreview(root, context) {
  const toolbar = root.querySelector('.cos-toolbar-actions');
  if (!toolbar) return { destroy() {} };
  toolbar.insertAdjacentHTML('beforeend', '<button type="button" data-open-page-package>Page package</button>');
  function mount() {
    root.querySelector('[data-page-package-dialog]')?.remove();
    root.insertAdjacentHTML('beforeend', renderPagePackageDialog(context.recordService.all(), context.getSelectedId?.()));
  }
  root.addEventListener('click', (event) => {
    if (event.target.closest('[data-open-page-package]')) { mount(); root.querySelector('[data-page-package-dialog]')?.showModal(); return; }
    if (event.target.closest('[data-download-page-package]')) {
      const record = context.recordService.get(context.getSelectedId?.());
      const packageData = buildGeneratedPagePackage(record, context.recordService.all());
      downloadText(packageData.html, packageData.filename, 'text/html');
      downloadText(JSON.stringify(packageData.publication, null, 2), `${safeName(record.id)}.publication.json`, 'application/json');
      return;
    }
    if (event.target.closest('[data-close-dialog]')) event.target.closest('dialog')?.close();
  });
  return { destroy() { root.querySelector('[data-open-page-package]')?.remove(); root.querySelector('[data-page-package-dialog]')?.remove(); } };
}

function downloadText(content, filename, type) { const blob = new Blob([content], { type }); const url = URL.createObjectURL(blob); const link = document.createElement('a'); link.href = url; link.download = filename; link.click(); URL.revokeObjectURL(url); }
function safeName(value) { return String(value || 'page').replace(/[^a-z0-9._-]+/gi, '-').replace(/^-+|-+$/g, '').toLowerCase(); }
function attr(value) { return escapeHtml(value).replaceAll('\n', '&#10;'); }
function escapeHtml(value) { return String(value || '').replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#039;'); }
